// Canonical slug normalizer
export function normalizeContentSlug(text) {
  if (!text) return '';
  return String(text)
    .toLowerCase()
    .replace(/[^\u0900-\u097F\w\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-');
}

