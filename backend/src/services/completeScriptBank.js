/**
 * Generates the full master repository of complete scripts across all 60 days.
 */
export function getAllCompleteScripts() {
  const scripts = [];

  // 1. Compile 60-day roadmap scripts
  CONTENT_BANK_60_DAYS.forEach((item, index) => {
    const day = item.day_number || (index + 1);
    scripts.push(buildFullFaceVideoScript(item, day));
  });

  return scripts;
}
