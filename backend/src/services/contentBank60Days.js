/**
 * Filter 60 Days Content Bank by search query, category, or phase
 */
export function get60DaysContentBank(query = {}) {
  const { search, category, phase } = query;
  let result = [...CONTENT_BANK_60_DAYS];

  if (category && category !== 'all') {
    result = result.filter(item => item.category === category);
  }

  if (phase && phase !== 'all') {
    result = result.filter(item => item.phase.includes(phase));
  }

  if (search && search.trim().length > 0) {
    const s = search.toLowerCase();
    result = result.filter(item =>
      item.title.toLowerCase().includes(s) ||
      item.hook.toLowerCase().includes(s) ||
      item.seo_keywords.toLowerCase().includes(s) ||
      item.screen_text.toLowerCase().includes(s) ||
      String(item.day_number).includes(s)
    );
  }

  return result;
}
